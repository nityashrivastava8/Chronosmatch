"""Summarise the SQLite ledger and export a SMALL sample that is safe to put on GitHub.

trades.db can be tens of MB (GitHub's web upload limit is 25 MB), so do not commit it -
it is regenerated by every demo run. Commit the summary / sample instead:

    python ledger_report.py                                   # print a summary of the latest run
    python ledger_report.py --csv docs/sample_trades.csv      # first 1,000 trades as CSV (~100 KB)
    python ledger_report.py --md docs/ledger_summary.md       # summary as a Markdown file
"""
import argparse
import csv
import os
import sqlite3
import sys

from config import DEFAULT_DB


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--run", type=int, default=None, help="run_id (default: latest run)")
    ap.add_argument("--csv", default=None, help="write a sample of trades to this CSV file")
    ap.add_argument("--rows", type=int, default=1000, help="rows in the CSV sample (default 1000)")
    ap.add_argument("--md", default=None, help="write the summary to this Markdown file")
    a = ap.parse_args()

    if not os.path.exists(a.db):
        sys.exit(f"{a.db} not found - run the demo first:  python engine_runner.py --spawn-feed --spawn-ledger --feed-duration 10")
    con = sqlite3.connect(a.db)
    run_id = a.run or con.execute("SELECT MAX(run_id) FROM trades").fetchone()[0]
    if run_id is None:
        sys.exit("ledger is empty")

    rows, vol, notional, pmin, pmax, pavg, takers = con.execute(
        "SELECT COUNT(*), SUM(qty), SUM(qty*price), MIN(price), MAX(price), AVG(price), COUNT(DISTINCT taker_id) "
        "FROM trades WHERE run_id=?", (run_id,)).fetchone()
    wait = con.execute("SELECT AVG(match_ns - order_ts_ns) FROM trades WHERE run_id=? "
                       "AND match_ns >= order_ts_ns AND order_ts_ns > 0", (run_id,)).fetchone()[0]
    top = con.execute("SELECT price, SUM(qty), COUNT(*) FROM trades WHERE run_id=? "
                      "GROUP BY price ORDER BY SUM(qty) DESC LIMIT 5", (run_id,)).fetchall()
    size_mb = os.path.getsize(a.db) / 1e6

    lines = [f"# Ledger summary (run {run_id})", "",
             "| metric | value |", "|---|---|",
             f"| trades stored | {rows:,} |",
             f"| distinct aggressing orders | {takers:,} |",
             f"| total volume (shares) | {vol:,} |",
             f"| price range (ticks) | {pmin} - {pmax} (average {pavg:,.1f}) |",
             f"| average wait before matching | {wait / 1000:,.1f} us |" if wait is not None else "| average wait before matching | n/a |",
             f"| database size | {size_mb:,.1f} MB |", "",
             "Busiest price levels:", "", "| price | volume | trades |", "|---:|---:|---:|"]
    lines += [f"| {p} | {v:,} | {c:,} |" for p, v, c in top]
    text = "\n".join(lines) + "\n"
    print(text)

    if a.md:
        os.makedirs(os.path.dirname(a.md) or ".", exist_ok=True)
        with open(a.md, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"wrote {a.md}")
    if a.csv:
        os.makedirs(os.path.dirname(a.csv) or ".", exist_ok=True)
        with open(a.csv, "w", newline="", encoding="utf-8") as f:
            w = csv.writer(f)
            w.writerow(["run_id", "seq", "taker_id", "maker_id", "price", "qty", "order_ts_ns", "match_ns"])
            w.writerows(con.execute("SELECT run_id, seq, taker_id, maker_id, price, qty, order_ts_ns, match_ns "
                                    "FROM trades WHERE run_id=? ORDER BY seq LIMIT ?", (run_id, a.rows)))
        print(f"wrote {a.csv} ({os.path.getsize(a.csv) / 1000:,.0f} KB, first {a.rows:,} trades)")
    con.close()


if __name__ == "__main__":
    main()